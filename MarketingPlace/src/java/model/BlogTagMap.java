public class BlogTagMap {

    private int tagId;
    private int blogId;

    public BlogTagMap() {
    }

    public BlogTagMap(int tagId, int blogId) {
        this.tagId = tagId;
        this.blogId = blogId;
    }

    public int getTagId() {
        return tagId;
    }

    public void setTagId(int tagId) {
        this.tagId = tagId;
    }

    public int getBlogId() {
        return blogId;
    }

    public void setBlogId(int blogId) {
        this.blogId = blogId;
    }

}
